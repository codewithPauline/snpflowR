test_that("simulation migration orientation is destination replacement", {
  initial <- rbind(rep(0, 10), rep(1, 10))
  forward <- matrix(c(0, 0, 1, 0), 2, 2)
  a <- simulate_snp_flow(10, generations = 1, initial = initial, migration = forward, seed = 1)
  expect_true(all(a$frequencies == 0))
  b <- simulate_snp_flow(10, generations = 1, initial = initial, migration = t(forward), seed = 1)
  expect_true(all(b$frequencies == 1))
  no_flow <- simulate_snp_flow(10, generations = 1, initial = initial, migration = matrix(0, 2, 2), seed = 1)
  expect_equal(unname(no_flow$frequencies), initial)
  expect_equal(a$truth$migration["A", "B"], 1)
})

test_that("simulation is reproducible and validates parameters", {
  a <- simulate_snp_flow(30, n_ind = c(10, 20), missing = .1, seed = 2)
  expect_identical(a, simulate_snp_flow(30, n_ind = c(10, 20), missing = .1, seed = 2))
  expect_equal(dim(a$genotypes), c(30, 30))
  expect_true(anyNA(a$genotypes))
  expect_true(all(a$frequencies >= 0 & a$frequencies <= 1))
  absent <- simulate_snp_flow(10, missing = 1, seed = 2)
  expect_true(all(absent$counts$called == 0))
  expect_error(simulate_snp_flow(migration = diag(2)), "zero diagonal")
  expect_error(simulate_snp_flow(n_ind = 4), "length two")
  expect_error(simulate_snp_flow(initial = matrix(2, 2, 200)), "frequency matrix")
  expect_error(simulate_snp_flow(generations = -1), "integer")
  expect_error(simulate_snp_flow(mutation = .7), "between")
  expect_error(simulate_snp_flow(n_loci = 0), "integer")
})
