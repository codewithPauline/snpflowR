test_that("GST matches independent heterozygosity calculations", {
  p <- c(.1, .3, .6, .9); q <- c(.4, .5, .7, .8)
  x <- make_counts(p, q)
  fit <- estimate_flow(x)
  expect_equal(unname(fit$directional_gst[1, 2]), reference_gst(p, q), tolerance = 1e-12)
  expect_equal(unname(fit$directional_gst[2, 1]), reference_gst(q, p), tolerance = 1e-12)
  expect_equal(unname(fit$pairwise_gst[1, 2]), reference_gst(p, q, FALSE), tolerance = 1e-12)
  expect_equal(fit$pairwise_gst, t(fit$pairwise_gst))
  expect_equal(fit$pairs$delta_gst, reference_gst(q, p) - reference_gst(p, q))
  expect_equal(max(fit$relative_migration, na.rm = TRUE), 1)
  expect_equal(fit$migration_transform[1, 2], (1 / fit$directional_gst[1, 2] - 1) / 4)
  expect_identical(fit$pairs$direction, "unresolved")
})

test_that("orientation and allele relabeling are consistent", {
  x <- make_counts()
  fit <- estimate_flow(x)
  flipped <- snp_counts(x$called - x$alt, x$called)
  expect_equal(estimate_flow(flipped)$directional_gst, fit$directional_gst)
  swapped <- snp_counts(x$alt[2:1, ], x$called[2:1, ])
  expect_equal(estimate_flow(swapped)$directional_gst, fit$directional_gst[2:1, 2:1])
  expect_equal(estimate_flow(swapped)$pairs$delta_gst, -fit$pairs$delta_gst)
  reordered <- snp_counts(x$alt[, 4:1], x$called[, 4:1])
  expect_equal(estimate_flow(reordered)$directional_gst, fit$directional_gst)
})

test_that("boundary and missing cases are explicit", {
  fit <- estimate_flow(make_counts(0, 1))
  expect_equal(fit$pairs$n_no_shared, 1)
  expect_true(is.na(fit$directional_gst[1, 2]))
  expect_equal(fit$pairwise_gst[1, 2], 1)
  expect_identical(fit$pairs$direction, "unresolved")
  identical_pops <- estimate_flow(make_counts(rep(.3, 30), rep(.3, 30)),
                                   n_boot = 399, resample = "locus", seed = 1)
  expect_equal(identical_pops$pairs$delta_gst, 0)
  expect_identical(identical_pops$pairs$reason, "singular_migration_transform")
  expect_true(is.infinite(identical_pops$migration_transform[1, 2]))
  expect_true(all(is.na(identical_pops$relative_migration)))
  mono <- estimate_flow(make_counts(c(0, 1), c(0, 1)))
  expect_equal(mono$pairs$n_shared_fixed, 2)
  expect_true(is.na(mono$pairs$delta_gst))
  x <- make_counts()
  x$alt[1, ] <- x$called[1, ] <- 0
  fit <- estimate_flow(x)
  expect_equal(fit$pairs$n_low_calls, 4)
  expect_identical(fit$pairs$reason, "undefined_differentiation")
})

test_that("bootstrap retains pairing and whole duplicated blocks", {
  x <- make_counts(seq(.05, .35, length.out = 24), seq(.3, .6, length.out = 24))
  fit <- estimate_flow(x, n_boot = 399, resample = "locus", seed = 99, keep_bootstrap = TRUE)
  idx <- rep(seq_len(24), each = 5)
  a <- x$alt[, idx]; n <- x$called[, idx]
  colnames(a) <- colnames(n) <- paste0("dup", seq_along(idx))
  duplicated <- snp_counts(a, n, blocks = idx)
  block <- estimate_flow(duplicated, n_boot = 399, resample = "block", seed = 99, keep_bootstrap = TRUE)
  expect_equal(fit$bootstrap, block$bootstrap, tolerance = 1e-12)
  expect_equal(fit$pairs$lower, block$pairs$lower)
  expect_equal(block$pairs$n_units, 24)
  naive <- estimate_flow(duplicated, n_boot = 399, resample = "locus", seed = 99)
  expect_lt(naive$pairs$upper - naive$pairs$lower, block$pairs$upper - block$pairs$lower)
  x$blocks <- rep("one", 24)
  one <- estimate_flow(x, n_boot = 399, seed = 2)
  expect_identical(one$pairs$reason, "insufficient_resampling_units")
  expect_identical(one$pairs$direction, "unresolved")
})

test_that("reporting safeguards apply to every pair", {
  x <- make_counts(rep(.05, 30), rep(.3, 30))
  expect_error(estimate_flow(x, n_boot = 399), "requires x\\$blocks")
  small <- estimate_flow(x, n_boot = 10, resample = "locus", seed = 1)
  expect_identical(small$pairs$direction, "unresolved")
  supported <- estimate_flow(x, n_boot = 399, resample = "locus", seed = 1)
  expect_identical(supported$pairs$direction, "A -> B")
  threshold <- estimate_flow(x, n_boot = 399, resample = "locus", seed = 1, min_effect = 1)
  expect_identical(threshold$pairs$direction, "unresolved")
  a <- rbind(x$alt, C = rep(700, 30))
  n <- matrix(1000, 3, 30, dimnames = dimnames(a))
  multi <- estimate_flow(snp_counts(a, n), n_boot = 399, resample = "locus", seed = 1)
  expect_equal(multi$settings$interval_level, 1 - .05 / 3)
  expect_true(all(multi$pairs$reason == "insufficient_tail_resolution"))
  expect_error(estimate_flow(x, conf_level = 1), "strictly")
  expect_error(estimate_flow(x, n_boot = 2.5), "integer")
  expect_error(estimate_flow(x, min_units = 1), "integer")
  expect_error(estimate_flow(x, keep_bootstrap = NA), "TRUE or FALSE")
})

test_that("seeded operations preserve the caller's random stream", {
  set.seed(721)
  before <- .Random.seed
  x <- simulate_snp_flow(n_loci = 30, seed = 4)$counts
  expect_identical(.Random.seed, before)
  a <- estimate_flow(x, n_boot = 50, resample = "locus", seed = 5, keep_bootstrap = TRUE)
  expect_identical(.Random.seed, before)
  b <- estimate_flow(x, n_boot = 50, resample = "locus", seed = 5, keep_bootstrap = TRUE)
  expect_identical(a$bootstrap, b$bootstrap)
  expect_output(print(a), "do not establish")
})

