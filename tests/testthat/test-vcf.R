test_that("VCF parsing aligns sample labels and preserves missing calls", {
  file <- system.file("extdata", "tiny.vcf", package = "snpflowR")
  pops <- c(b2 = "B", a2 = "A", b1 = "B", a1 = "A")
  x <- read_snp_vcf(file, pops, block_size = 20, chunk_size = 1)
  expect_equal(unname(x$alt), rbind(c(1, 1, 2), c(3, 3, 1)))
  expect_equal(unname(x$called), rbind(c(4, 2, 2), c(4, 4, 4)))
  expect_equal(unname(x$import$audit), c(5, 3, 1, 1, 2, 1))
  expect_identical(x$blocks, c("1:0", "1:0", "1:1"))
  expect_equal(ncol(read_snp_vcf(file, pops, pass_only = FALSE)$alt), 4)
  expect_error(read_snp_vcf(file, c(a1 = "A", b1 = "B")), "every VCF sample")
  expect_error(read_snp_vcf(file, c("A", "A", "B", "B")), "sample IDs")
  compressed <- tempfile(fileext = ".vcf.gz")
  on.exit(unlink(compressed), add = TRUE)
  con <- gzfile(compressed, "wt"); writeLines(readLines(file), con); close(con)
  expect_equal(read_snp_vcf(compressed, pops)$alt, x$alt)
})

test_that("VCF rejects malformed retained genotypes and duplicate records", {
  source <- readLines(system.file("extdata", "tiny.vcf", package = "snpflowR"))
  pops <- c(a1 = "A", a2 = "A", b1 = "B", b2 = "B")
  file <- tempfile(fileext = ".vcf")
  on.exit(unlink(file), add = TRUE)
  for (bad in c("0", "0/1/1", "0/2", "1/./0", "x/y")) {
    lines <- source; lines[5] <- sub("0/0", bad, lines[5], fixed = TRUE)
    writeLines(lines, file)
    expect_error(read_snp_vcf(file, pops), "Unsupported or malformed")
  }
  writeLines(c(source, source[5]), file)
  expect_error(read_snp_vcf(file, pops), "Duplicate")
  writeLines(source[-1], file)
  expect_error(read_snp_vcf(file, pops), "fileformat")
  writeLines(source[1:3], file)
  expect_error(read_snp_vcf(file, pops), "no #CHROM")
  lines <- source; lines[5] <- sub("\tGT\t", "\tDP:GT\t", lines[5])
  writeLines(lines, file)
  expect_error(read_snp_vcf(file, pops), "first FORMAT")
  writeLines(c(source[1:4], source[8:9]), file)
  expect_error(read_snp_vcf(file, pops), "No usable")
})
